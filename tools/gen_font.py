CELL_W, CELL_H = 8, 16
LEFT_BEARING = 1        # blank column down the left of every cell
TOP_LEADING = 3         # blank rows above the cap line


def build():
    font = bytearray(256 * CELL_H)
    for ch, art in GLYPHS.items():
        rows = art.split('/')
        assert len(rows) == 9, f"{ch!r} has {len(rows)} rows"
        code = ord(ch)
        for y, row in enumerate(rows):
            assert len(row) == 5, f"{ch!r} row {y} is {len(row)} wide"
            bits = 0
            for x, c in enumerate(row):
                if c == '#':
                    # bit 7 is the leftmost pixel
                    bits |= 1 << (7 - (x + LEFT_BEARING))
            dst = TOP_LEADING + y
            if dst < CELL_H:
                font[code * CELL_H + dst] = bits
    return font


def main():
    font = build()
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, 'src', 'js', 'font.js')
    hexed = font.hex()
    lines = [hexed[i:i + 96] for i in range(0, len(hexed), 96)]
    with open(out, 'w') as f:
        f.write("// 8x16 text font, generated by tools/gen_font.py -- edit the glyphs there.\n"
                "//\n"
                "// A guest that draws its own text asks the BIOS for a font pointer and\n"
                "// renders through it (INT 10h AH=11h AL=30h).  Without a table to hand out,\n"
                "// everything such a guest writes is invisible, which is what made the Windows\n"
                "// boot manager's menu and its error messages render as a blank screen.\n"
                "//\n"
                "// One byte per scan line, sixteen per character, bit 7 leftmost.\n"
                "export const FONT_8X16 = Uint8Array.from(\n"
                # The concatenation has to be parenthesised: member access binds
                # tighter than +, so `'a' + 'b'.match(...)` matches only 'b'.
                "  ('" + "' +\n   '".join(lines) + "')\n"
                "    .match(/../g).map((b) => parseInt(b, 16)));\n"
                "\n"
                "export const FONT_HEIGHT = 16;\n")
    print(f"wrote {out}: {len(font)} bytes, {len(GLYPHS)} glyphs")


if __name__ == '__main__':
    main()
