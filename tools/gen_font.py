"""Generate the 8x16 VGA text font.

The emulator draws text mode host-side, so no glyph bitmaps ever existed here.
A guest that renders its own text needs them: it asks the BIOS for a font
pointer (INT 10h AH=11h AL=30h) and draws through it, so with no table to hand
out, everything it writes is invisible.  That is what left the Windows boot
manager's menu, countdown and error messages rendering as a blank screen.

Glyphs are authored on a 5x9 grid -- seven rows above the baseline and two
below it for descenders -- and placed into the 8x16 cell with one column of
left bearing and three rows of leading.  That leaves the cell's outermost row
and column clear, so adjacent characters never touch.

Bit 7 of each byte is the leftmost pixel, which is the order the hardware
scans and therefore the order a guest expects.
"""
