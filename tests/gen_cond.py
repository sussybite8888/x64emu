#!/usr/bin/env python3
"""Generate SETcc and CMOVcc tests across every condition and a spread of flag
states.

The signed conditions depend on SF against OF rather than on either alone, so a
condition table that confuses the two still passes every unsigned test.  Each of
the sixteen conditions is therefore evaluated against flag states that separate
those cases: SF set without OF, OF set without SF, and both together.
"""

import os

CF, PF, ZF, SF, OF = 0x001, 0x004, 0x040, 0x080, 0x800
BASE = 0x202                       # reserved bit 1, interrupts left enabled

# each entry: (suffix, predicate over the flag word)
CONDS = [
    ('o',  lambda f: bool(f & OF)),
    ('no', lambda f: not f & OF),
    ('b',  lambda f: bool(f & CF)),
    ('ae', lambda f: not f & CF),
    ('e',  lambda f: bool(f & ZF)),
    ('ne', lambda f: not f & ZF),
    ('be', lambda f: bool(f & CF) or bool(f & ZF)),
    ('a',  lambda f: not f & CF and not f & ZF),
    ('s',  lambda f: bool(f & SF)),
    ('ns', lambda f: not f & SF),
    ('p',  lambda f: bool(f & PF)),
    ('np', lambda f: not f & PF),
    ('l',  lambda f: bool(f & SF) != bool(f & OF)),
    ('ge', lambda f: bool(f & SF) == bool(f & OF)),
    ('le', lambda f: bool(f & ZF) or (bool(f & SF) != bool(f & OF))),
    ('g',  lambda f: not f & ZF and (bool(f & SF) == bool(f & OF))),
]

# states chosen to pull SF and OF apart, which is what the signed conditions
# actually test
STATES = [0, CF, ZF, SF, OF, SF | OF, CF | ZF | PF]

KEEP = 0x1111111111111111
MOVE = 0x2222222222222222


def emit(kind):
    blocks, checks, code = [], [], 1
    for state in STATES:
        f = BASE | state
        for suf, pred in CONDS:
            want = pred(state)
            b = [f'        movabs  $0x{f:x}, %rax',
                 '        push    %rax',
                 '        popfq']
            if kind == 'set':
                b.append('        mov     $0xff, %cl')
                b.append(f'        set{suf}   %cl')
                b.append(f'        cmp     ${1 if want else 0}, %cl')
                desc = f'set{suf} flags=0x{state:x} -> {int(want)}'
            else:
                b.append(f'        movabs  $0x{KEEP:x}, %rax')
                b.append(f'        movabs  $0x{MOVE:x}, %rbx')
                b.append(f'        cmov{suf}  %rbx, %rax')
                b.append(f'        movabs  $0x{MOVE if want else KEEP:x}, %rcx')
                b.append('        cmp     %rcx, %rax')
                desc = f'cmov{suf} flags=0x{state:x} -> {"move" if want else "keep"}'
            b.append(f'        mov     ${code}, %bl')
            b.append('        jne     fail')
            checks.append((code, desc))
            code += 1
            blocks.append('\n'.join(b))
    return blocks, checks, code


HEADER = '''// {what} across every condition.
//
// Generated by tests/gen_cond.py.  The flag states deliberately separate SF
// from OF, because the signed conditions are defined by those two against each
// other -- a table that mixes them up still passes every unsigned case.
        .code64
        .text
        .globl  _start
_start:
        mov     $0x8000, %rsp
'''

TAIL = '''
        xor     %eax, %eax
        out     %al, $0xE9
        hlt
fail:
        mov     %bl, %al
        out     %al, $0xE9
        hlt
'''

if __name__ == '__main__':
    here = os.path.dirname(os.path.abspath(__file__))
    for fname, kind, what in [('t_setcc', 'set', 'SETcc'),
                              ('t_cmov', 'cmov', 'CMOVcc')]:
        blocks, checks, code = emit(kind)
        if code > 255:
            raise SystemExit(f'{fname}: {code} checks exceed the byte exit code')
        with open(os.path.join(here, 'asm', f'{fname}.s'), 'w') as fh:
            fh.write(HEADER.format(what=what) + '\n'.join(blocks) + TAIL)
        with open(os.path.join(here, 'asm', f'{fname}.checks'), 'w') as fh:
            for n, desc in checks:
                fh.write(f'{n}\t{desc}\n')
        print(f'{fname}: {len(blocks)} blocks, {code - 1} checks')
