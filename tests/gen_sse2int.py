#!/usr/bin/env python3
"""Generate correctness tests for the SSE2 integer instructions.

The expected values come from a model of the manual written out below, not from
the emulator.  The model was also checked against an x86-64 CPU: on a machine
that can run x86-64 code (natively, or under Rosetta on Apple silicon),
`python3 tests/gen_sse2int.py --verify` builds the same cases into a native
program and compares every result with the model's.

These are the instructions glibc's SSE2 string functions are made of -- its
strlen is PMINUB and PCMPEQB -- so a mistake here kills a Linux userspace in its
first process.  Saturation and the signedness of each lane are where they go
wrong, so the inputs lean on the boundary values.
"""

import os
import random
import subprocess
import sys
import tempfile


def lanes(v, w):
    return [(v >> (8 * w * i)) & ((1 << (8 * w)) - 1) for i in range(16 // w)]


def join(ls, w):
    out = 0
    for i, x in enumerate(ls):
        out |= (x & ((1 << (8 * w)) - 1)) << (8 * w * i)
    return out


def sx(x, w):
    bits = 8 * w
    return x - (1 << bits) if x & (1 << (bits - 1)) else x


def clamp(v, lo, hi):
    return max(lo, min(hi, v))


def lanewise(w, fn):
    return lambda d, s: join([fn(a, b) for a, b in zip(lanes(d, w), lanes(s, w))], w)


def signed_lanewise(w, fn):
    return lanewise(w, lambda a, b: fn(sx(a, w), sx(b, w)))


def pack(win, wout, lo, hi):
    def f(d, s):
        ins = [sx(x, win) for x in lanes(d, win)] + [sx(x, win) for x in lanes(s, win)]
        return join([clamp(x, lo, hi) for x in ins], wout)
    return f


def pmuludq(d, s):
    dl, sl = lanes(d, 4), lanes(s, 4)
    return join([dl[0] * sl[0], dl[2] * sl[2]], 8)


def pmaddwd(d, s):
    dl, sl = lanes(d, 2), lanes(s, 2)
    return join([sx(dl[2 * i], 2) * sx(sl[2 * i], 2) +
                 sx(dl[2 * i + 1], 2) * sx(sl[2 * i + 1], 2) for i in range(4)], 4)


def psadbw(d, s):
    dl, sl = lanes(d, 1), lanes(s, 1)
    return join([sum(abs(dl[h * 8 + j] - sl[h * 8 + j]) for j in range(8))
                 for h in range(2)], 8)


# mnemonic -> model of dst op= src
OPS = {
    'paddusb':  lanewise(1, lambda a, b: min(a + b, 0xff)),
    'paddusw':  lanewise(2, lambda a, b: min(a + b, 0xffff)),
    'psubusb':  lanewise(1, lambda a, b: max(a - b, 0)),
    'psubusw':  lanewise(2, lambda a, b: max(a - b, 0)),
    'paddsb':   signed_lanewise(1, lambda a, b: clamp(a + b, -128, 127)),
    'paddsw':   signed_lanewise(2, lambda a, b: clamp(a + b, -32768, 32767)),
    'psubsb':   signed_lanewise(1, lambda a, b: clamp(a - b, -128, 127)),
    'psubsw':   signed_lanewise(2, lambda a, b: clamp(a - b, -32768, 32767)),
    'pminub':   lanewise(1, min),
    'pmaxub':   lanewise(1, max),
    'pminsw':   signed_lanewise(2, min),
    'pmaxsw':   signed_lanewise(2, max),
    'pavgb':    lanewise(1, lambda a, b: (a + b + 1) >> 1),
    'pavgw':    lanewise(2, lambda a, b: (a + b + 1) >> 1),
    'pmullw':   lanewise(2, lambda a, b: a * b),
    'pmulhuw':  lanewise(2, lambda a, b: (a * b) >> 16),
    'pmulhw':   signed_lanewise(2, lambda a, b: (a * b) >> 16),
    'pmuludq':  pmuludq,
    'pmaddwd':  pmaddwd,
    'psadbw':   psadbw,
    'packsswb': pack(2, 1, -128, 127),
    'packuswb': pack(2, 1, 0, 255),
    'packssdw': pack(4, 2, -32768, 32767),
}

EDGE = [0x7f80ff007f80ff00_ff007f80ff007f80,
        0x7fff8000ffff0000_00007fff8000ffff,
        0x80008000800080007fff7fff7fff7fff,
        0xffffffffffffffff_0000000000000000,
        0x0102030405060708_f0e0d0c0b0a09080]


def cases(seed=1):
    rnd = random.Random(seed)
    out = []
    for op in OPS:
        pairs = [(EDGE[0], EDGE[1]), (EDGE[1], EDGE[0]), (EDGE[2], EDGE[3]),
                 (EDGE[4], EDGE[2]),
                 (rnd.getrandbits(128), rnd.getrandbits(128)),
                 (rnd.getrandbits(128), rnd.getrandbits(128))]
        for d, s in pairs:
            out.append((op, d, s, OPS[op](d, s) & ((1 << 128) - 1)))
    return out


# PINSRW, PEXTRW, MASKMOVDQU and the E6 conversions, with fixed inputs
PINSRW = [(0x0123456789abcdef_fedcba9876543210, 0xbeef, imm) for imm in (0, 3, 5, 7)]
PEXTRW = [(0x0123456789abcdef_fedcba9876543210, imm) for imm in (0, 2, 4, 7)]


def pinsrw(v, word, imm):
    m = 0xffff << (16 * imm)
    return (v & ~m) | (word << (16 * imm))


HEADER = '''// SSE2 integer instructions: saturating add and subtract, min and max,
// average, the multiplies, the packs, PMADDWD, PSADBW, PINSRW, PEXTRW,
// MASKMOVDQU, the 0F E6 conversions, RCP and RSQRT.
//
// Generated by tests/gen_sse2int.py from a model of the manual, which was
// itself checked against an x86-64 CPU.  Every other case reads its source
// from memory rather than a register, so both operand paths are exercised.
        .code64
        .text
        .globl  _start
_start:
        mov     $0x8000, %rsp
'''

TAIL = '''
        xor     %eax, %eax
        out     %al, $0xE9
        hlt
fail:
        mov     %bl, %al
        out     %al, $0xE9
        hlt
'''


def q(v):
    return f'        .quad   0x{v & 0xffffffffffffffff:016x}, 0x{v >> 64:016x}'


def emit():
    code, data, checks = [], [], []
    n = 1

    def check128(label):
        nonlocal n
        code.extend([
            '        movdqu  %xmm0, out(%rip)',
            f'        mov     ${n}, %bl',
            '        mov     out(%rip), %rax',
            f'        cmp     {label}(%rip), %rax',
            '        jne     fail',
            '        mov     out+8(%rip), %rax',
            f'        cmp     {label}+8(%rip), %rax',
            '        jne     fail',
        ])

    for i, (op, d, s, r) in enumerate(cases()):
        code.append(f'        movdqu  c{n}_d(%rip), %xmm0')
        if i % 2:
            code.append(f'        {op:8} c{n}_s(%rip), %xmm0')
        else:
            code.append(f'        movdqu  c{n}_s(%rip), %xmm1')
            code.append(f'        {op:8} %xmm1, %xmm0')
        check128(f'c{n}_r')
        data += [f'c{n}_d:', q(d), f'c{n}_s:', q(s), f'c{n}_r:', q(r)]
        checks.append((n, f'{op} {"mem" if i % 2 else "reg"} -> 0x{r:032x}'))
        n += 1

    for v, word, imm in PINSRW:
        code.append(f'        movdqu  c{n}_d(%rip), %xmm0')
        if imm % 2:
            code.append(f'        movw    $0x{word:x}, w16(%rip)')
            code.append(f'        pinsrw  ${imm}, w16(%rip), %xmm0')
        else:
            code.append(f'        mov     $0x1234{word:04x}, %eax')
            code.append(f'        pinsrw  ${imm}, %eax, %xmm0')
        r = pinsrw(v, word, imm)
        check128(f'c{n}_r')
        data += [f'c{n}_d:', q(v), f'c{n}_r:', q(r)]
        checks.append((n, f'pinsrw ${imm} -> 0x{r:032x}'))
        n += 1

    for v, imm in PEXTRW:
        r = (v >> (16 * imm)) & 0xffff
        code.extend([
            f'        movdqu  c{n}_d(%rip), %xmm1',
            '        movabs  $-1, %rax',
            f'        pextrw  ${imm}, %xmm1, %eax',
            f'        mov     ${n}, %bl',
            f'        cmp     $0x{r:x}, %rax',                 # zero-extended
            '        jne     fail',
        ])
        data += [f'c{n}_d:', q(v)]
        checks.append((n, f'pextrw ${imm} -> 0x{r:x}'))
        n += 1

    # MASKMOVDQU: bytes 1, 4-6 and 15 selected
    src, maskv = 0x00112233445566778899aabbccddeeff, 0x80000000000000ff80ff8000000080ff
    fill = 0x5a5a5a5a5a5a5a5a5a5a5a5a5a5a5a5a
    r = 0
    for i in range(16):
        b = (src if (maskv >> (8 * i + 7)) & 1 else fill) >> (8 * i) & 0xff
        r |= b << (8 * i)
    code.extend([
        f'        movdqu  c{n}_f(%rip), %xmm2',
        '        movdqu  %xmm2, buf(%rip)',
        f'        movdqu  c{n}_d(%rip), %xmm0',
        f'        movdqu  c{n}_m(%rip), %xmm1',
        '        lea     buf(%rip), %rdi',
        '        maskmovdqu %xmm1, %xmm0',
        '        movdqu  buf(%rip), %xmm0',
    ])
    check128(f'c{n}_r')
    data += [f'c{n}_d:', q(src), f'c{n}_m:', q(maskv), f'c{n}_f:', q(fill), f'c{n}_r:', q(r)]
    checks.append((n, f'maskmovdqu -> 0x{r:032x}'))
    n += 1

    # 0F E6.  CVTPD2DQ rounds to even, CVTTPD2DQ truncates, and a value that
    # does not fit becomes 0x80000000; CVTDQ2PD reads only the low 64 bits.
    import struct
    def dbl(x):
        return struct.unpack('<Q', struct.pack('<d', x))[0]
    for mn, a, b, lo, hi in [('cvttpd2dq', 2.5, -3.7, 2, -3),
                             ('cvtpd2dq', 2.5, -3.7, 2, -4),
                             ('cvtpd2dq', 3.5, 1e10, 4, -0x80000000)]:
        v = dbl(a) | dbl(b) << 64
        r = (lo & 0xffffffff) | (hi & 0xffffffff) << 32
        code.append(f'        movdqu  c{n}_d(%rip), %xmm0')
        code.append(f'        {mn:8} %xmm0, %xmm0')
        check128(f'c{n}_r')
        data += [f'c{n}_d:', q(v), f'c{n}_r:', q(r)]
        checks.append((n, f'{mn} {a},{b} -> {lo},{hi}'))
        n += 1
    v = (7 & 0xffffffff) | ((-9) & 0xffffffff) << 32 | 0xdeadbeef << 64
    r = dbl(7.0) | dbl(-9.0) << 64
    code.append(f'        movdqu  c{n}_d(%rip), %xmm0')
    code.append('        cvtdq2pd %xmm0, %xmm0')
    check128(f'c{n}_r')
    data += [f'c{n}_d:', q(v), f'c{n}_r:', q(r)]
    checks.append((n, 'cvtdq2pd 7,-9'))
    n += 1

    # RCPSS and RSQRTSS are approximations on hardware: within 1.5 * 2^-12
    code.extend([
        '        movss   four(%rip), %xmm1',
        '        rcpss   %xmm1, %xmm0',
        '        rsqrtss %xmm1, %xmm2',
        f'        mov     ${n}, %bl',
        '        ucomiss rcp_lo(%rip), %xmm0',
        '        jb      fail',
        '        ucomiss rcp_hi(%rip), %xmm0',
        '        ja      fail',
        f'        mov     ${n + 1}, %bl',
        '        ucomiss rsq_lo(%rip), %xmm2',
        '        jb      fail',
        '        ucomiss rsq_hi(%rip), %xmm2',
        '        ja      fail',
    ])
    checks.append((n, 'rcpss 4.0 ~ 0.25'))
    checks.append((n + 1, 'rsqrtss 4.0 ~ 0.5'))
    n += 2
    data += ['four:   .float  4.0', 'rcp_lo: .float  0.2499', 'rcp_hi: .float  0.2501',
             'rsq_lo: .float  0.4998', 'rsq_hi: .float  0.5002']

    assert n < 255, 'check numbers must fit the one-byte status'
    text = HEADER + '\n'.join(code) + TAIL + '\n        .align  16\nout:    .quad   0, 0\n' + \
        'buf:    .quad   0, 0\nw16:    .word   0\n        .align  16\n' + '\n'.join(data) + '\n'
    return text, checks


def verify():
    """Compare the model with an x86-64 CPU, case by case."""
    cs = cases()
    lines = ['#include <stdio.h>', '#include <string.h>', 'typedef unsigned char u8;',
             'static u8 d[16] __attribute__((aligned(16))), s[16] __attribute__((aligned(16)));',
             'int main(void) {']
    for op, dv, sv, _ in cs:
        lines.append('{ u8 dd[] = {%s}, ss[] = {%s}; memcpy(d, dd, 16); memcpy(s, ss, 16);' % (
            ','.join(str(dv >> (8 * i) & 0xff) for i in range(16)),
            ','.join(str(sv >> (8 * i) & 0xff) for i in range(16))))
        lines.append('  __asm__ volatile("movdqu (%%0), %%%%xmm0\\n movdqu (%%1), %%%%xmm1\\n '
                     '%s %%%%xmm1, %%%%xmm0\\n movdqu %%%%xmm0, (%%0)" :: "r"(d), "r"(s) '
                     ': "xmm0", "xmm1", "memory");' % op)
        lines.append('  for (int i = 15; i >= 0; i--) printf("%02x", d[i]); printf("\\n"); }')
    lines.append('return 0; }')
    with tempfile.TemporaryDirectory() as tmp:
        src, exe = os.path.join(tmp, 'v.c'), os.path.join(tmp, 'v')
        open(src, 'w').write('\n'.join(lines))
        subprocess.run(['clang', '-arch', 'x86_64', '-O0', src, '-o', exe], check=True)
        got = subprocess.run(['arch', '-x86_64', exe], check=True,
                             capture_output=True, text=True).stdout.split()
    bad = [(op, d, s, r, int(g, 16)) for (op, d, s, r), g in zip(cs, got) if int(g, 16) != r]
    for op, d, s, r, g in bad:
        print(f'{op}: d={d:032x} s={s:032x} model={r:032x} cpu={g:032x}')
    print(f'{len(cs) - len(bad)} of {len(cs)} cases agree with the CPU')
    return not bad


if __name__ == '__main__':
    if '--verify' in sys.argv:
        sys.exit(0 if verify() else 1)
    here = os.path.dirname(os.path.abspath(__file__))
    text, checks = emit()
    open(os.path.join(here, 'asm', 't_sse2int.s'), 'w').write(text)
    with open(os.path.join(here, 'asm', 't_sse2int.checks'), 'w') as f:
        for code, desc in checks:
            f.write(f'{code}\t{desc}\n')
    print(f'wrote t_sse2int.s ({len(checks)} checks)')
