// SSE2 integer operations, which is where a software AES-GCM spends its time.
//
// Expected values are computed independently rather than read back from this
// emulator, so a wrong lane order or a dropped operand fails a check instead of
// quietly agreeing with itself.  PADDQ and PSUBQ are absent from the CPU and so
// are not exercised here.
        .code64
        .text
        .globl  _start

.macro  wantx   label, code
        movdqu  %xmm0, out(%rip)
        mov     out(%rip), %rax
        mov     \label(%rip), %rdx
        cmp     %rdx, %rax
        mov     $\code, %bl
        jne     fail
        mov     out+8(%rip), %rax
        mov     \label+8(%rip), %rdx
        cmp     %rdx, %rax
        jne     fail
.endm

_start:
