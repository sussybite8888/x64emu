        por     %xmm1, %xmm0
        wantx   e_por, 2

        movdqu  va(%rip), %xmm0
        movdqu  vb(%rip), %xmm1
        pxor    %xmm1, %xmm0
        wantx   e_pxor, 3

        movdqu  va(%rip), %xmm0
        movdqu  vb(%rip), %xmm1
        pandn   %xmm0, %xmm1
        movdqa  %xmm1, %xmm0
        wantx   e_pandn, 4

        movdqu  va(%rip), %xmm0
        movdqu  vb(%rip), %xmm1
        paddb   %xmm1, %xmm0
        wantx   e_paddb, 5

        movdqu  va(%rip), %xmm0
        movdqu  vb(%rip), %xmm1
        psubb   %xmm1, %xmm0
        wantx   e_psubb, 6

        movdqu  va(%rip), %xmm0
        movdqu  vb(%rip), %xmm1
        pcmpeqb %xmm1, %xmm0
        wantx   e_pcmpeqb, 7

        movdqu  va(%rip), %xmm0
        movdqu  vb(%rip), %xmm1
        pslldq  $5, %xmm0
        wantx   e_pslldq5, 8

        movdqu  va(%rip), %xmm0
        movdqu  vb(%rip), %xmm1
        psrldq  $5, %xmm0
        wantx   e_psrldq5, 9

        movdqu  va(%rip), %xmm0
        movdqu  vb(%rip), %xmm1
        psllq   $7, %xmm0
        wantx   e_psllq7, 10

        movdqu  va(%rip), %xmm0
        movdqu  vb(%rip), %xmm1
