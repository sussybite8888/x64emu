        movdqu  va(%rip), %xmm0
        movdqu  vb(%rip), %xmm1
        punpcklqdq%xmm1, %xmm0
        wantx   e_punpcklqdq, 12

        movdqu  va(%rip), %xmm0
        movdqu  vb(%rip), %xmm1
        punpckhqdq%xmm1, %xmm0
        wantx   e_punpckhqdq, 13

        movdqu  va(%rip), %xmm0
        movdqu  vb(%rip), %xmm1
        punpcklbw%xmm1, %xmm0
        wantx   e_punpcklbw, 14

        movdqu  va(%rip), %xmm0
        movdqu  vb(%rip), %xmm1
        pshufd  $0x1b, %xmm0, %xmm0
        wantx   e_pshufd1b, 15

        movdqu  va(%rip), %xmm0
        pmovmskb %xmm0, %eax
        cmp     $0xff00, %eax
        mov     $16, %bl
        jne     fail

        xor     %eax, %eax
        out     %al, $0xE9
        hlt
fail:
